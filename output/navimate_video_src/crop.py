import sys
from PIL import Image
src, dst = sys.argv[1], sys.argv[2]
C = {10:(.03,.22,.95,1),11:(.05,.21,.96,.98),12:(.593,0,1,1),13:(.593,0,1,1),14:(.04,.38,1,.97),15:(.04,.20,.99,.97),
     16:(.04,.20,.99,.80),17:(.05,.205,.97,.99),18:(.05,.21,.98,.99),19:(.04,.19,.97,.83),20:(.05,.21,.99,.583),
     22:(.04,.15,.98,.93),23:(.07,.19,.96,.84),24:(.04,.25,.96,.68),26:(.04,.22,.98,.91),27:(.05,.21,.97,.97),
     28:(.04,.22,.98,.87),29:(.04,.21,.98,.97),31:(.04,.20,.97,.96),32:(.02,.74,.97,.96),33:(.04,.22,.97,.74),
     34:(.06,.21,.93,.95),35:(.03,.21,.97,.85)}
EXTRA = {'s32a':(32,(.02,.195,.97,.48))}
jobs = [('s%02d' % k, k, b) for k, b in C.items()] + [(n, k, b) for n, (k, b) in EXTRA.items()]
for name, k, (a, b, c, d) in jobs:
    im = Image.open(f'{src}/hi-{k:02d}.png').convert('RGB'); W, H = im.size
    im.crop((int(a*W), int(b*H), int(c*W), int(d*H))).save(f'{dst}/{name}.jpg', quality=92)
print('ok', len(jobs))
